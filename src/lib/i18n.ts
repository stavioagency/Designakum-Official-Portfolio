const DICT = { ar, en } as const;

export type Dictionary = typeof ar;

/**
 * Fills `{name}`-style holes in a dictionary string.
 *
 * The dictionary holds strings, never functions, because a slice of it is handed
 * to client components and a function cannot cross that boundary — a template
 * function here fails at render time, not at build time, which is the worst
 * place to find out.
 */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key) =>
    key in values ? String(values[key]) : whole,
  );
}

export function dict(locale: Locale): Dictionary {
  return DICT[locale] ?? DICT.ar;
}
