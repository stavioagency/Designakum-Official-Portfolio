#!/usr/bin/env node
/**
 * Writes down which brand files exist, at build time.
 *
 * `brandAsset()` used to answer this with `fs.existsSync` against
 * `public/brand`. That works on a machine with a disk and stops working the
 * moment the app is bundled — on Workers `public/` is served by the platform's
 * asset system and is not a filesystem path at all, so every lookup would come
 * back empty and every logo would silently fall back to type.
 *
 * Scanning once at build and emitting a plain object keeps the lookup
 * synchronous, which matters because it is called from components that are not
 * async and from `pricing-copy`, which is on the landing page's hot path.
 */
import fs from "node:fs";
import path from "node:path";

const DIR = path.join(process.cwd(), "public", "brand");
const OUT = path.join(process.cwd(), "src", "lib", "brand-manifest.ts");
const EXTENSIONS = [".svg", ".png", ".webp", ".jpg", ".jpeg", ".avif"];

const found = {};
if (fs.existsSync(DIR)) {
  for (const file of fs.readdirSync(DIR).sort()) {
    const ext = path.extname(file).toLowerCase();
    if (!EXTENSIONS.includes(ext)) continue;
    const base = path.basename(file, ext);
    // First extension in EXTENSIONS order wins, so a PNG never beats an SVG.
    if (found[base] && EXTENSIONS.indexOf(ext) >= EXTENSIONS.indexOf(path.extname(found[base]))) {
      continue;
    }
    found[base] = `/brand/${file}`;
  }
}

const body = `// Generated by scripts/brand-manifest.mjs — do not edit.
// Regenerated on every build; run \`npm run brand:manifest\` after changing
// anything in public/brand/.

export const BRAND_MANIFEST: Record<string, string> = ${JSON.stringify(found, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`brand manifest: ${Object.keys(found).length} files`);
